// After `expo export`: keep the test pages in dist/lab/ only in a DEV build.
//
// public/lab/ holds pages for trying things on a real phone before the app
// uses them (Phase 0 of docs/end-to-end-encryption.md: how fast a phone
// locks and unlocks, and runs search on the device). They are for the
// owner's DEV address, never asklocker.com.
//
// The safe direction is to remove them: they stay only when the build
// names the DEV project (EXPO_PUBLIC_SUPABASE_URL, the value that decides
// whose data a build reaches; see src/lib/environment.ts). PROD, a missing
// URL or an unknown project: dist/lab/ is deleted.
//
// In a DEV build, the lab gets dist/lab/vault-crypto.js: the real
// supabase/functions/_shared/vault-crypto.ts with its types taken out by
// Node itself, so the page measures the code the app will run, not a copy.
//
//   node scripts/lab-pages.mjs [dist]

import { existsSync, readFileSync, rmSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import * as nodeModule from 'node:module';

const DEV_REF = 'tkqsfoppwlyupentuixy';
const dist = process.argv[2] ?? 'dist';
const lab = join(dist, 'lab');

// `expo export` reads .env itself; this separate step reads it too, without
// overriding a value the host already set.
if (existsSync('.env') && typeof process.loadEnvFile === 'function') {
  try { process.loadEnvFile('.env'); } catch { /* unreadable: the host's values stand */ }
}

if (!existsSync(lab)) {
  console.log(`[lab] No ${lab}; nothing to do.`);
  process.exit(0);
}

const url = process.env.EXPO_PUBLIC_SUPABASE_URL ?? '';
if (!url.includes(DEV_REF)) {
  rmSync(lab, { recursive: true, force: true });
  console.log(`[lab] Not a DEV build (${url ? 'another project' : 'no Supabase URL'}): removed ${lab}.`);
  process.exit(0);
}

const strip = nodeModule.stripTypeScriptTypes;
if (typeof strip !== 'function') {
  rmSync(lab, { recursive: true, force: true });
  console.log(`[lab] This Node cannot take types out of TypeScript (22.13 or later can): removed ${lab}.`);
  process.exit(0);
}

const source = readFileSync('supabase/functions/_shared/vault-crypto.ts', 'utf8');
const js = strip(source, { mode: 'strip' });
writeFileSync(join(lab, 'vault-crypto.js'),
  `// Generated by scripts/lab-pages.mjs from supabase/functions/_shared/vault-crypto.ts. Do not edit.\n${js}`);
console.log(`[lab] DEV build: kept ${lab}, with vault-crypto.js.`);
